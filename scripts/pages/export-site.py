#!/usr/bin/env python3
"""Export the shared stylesheet and the footer-page text from the mockups into the live site.

The mockups stay the design source: run this after changing them or content.py.
  python3 scripts/pages/export-site.py
Writes apps/site/static/css/site.css, apps/site/src/content/pages.json and copies images.
"""
import importlib.util, json, os, re, shutil
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
MOCK = os.path.join(ROOT, 'mockups')
SITE = os.path.join(ROOT, 'apps', 'site')

# 1. CSS: the generated footer pages carry the full shared style (tokens, header, strip, footer,
#    doc layout, donate modal, agent resources card) in one <style> block.
html = open(os.path.join(MOCK, 'how-it-works.html')).read()
css = re.search(r'<style>\n(.*?)</style>', html, re.S).group(1)
css = css.replace('url(img/', 'url(/img/')
open(os.path.join(SITE, 'static', 'css', 'site.css'), 'w').write('/* generated by scripts/pages/export-site.py from mockups/how-it-works.html; edit the mockups, not this file */\n' + css)

# 2. Page text.
spec = importlib.util.spec_from_file_location('c', os.path.join(HERE, 'content.py'))
c = importlib.util.module_from_spec(spec); spec.loader.exec_module(c)
def fix(s):  # mockup links → site routes
    s = re.sub(r'href="([a-z0-9-]+)\.html(#[^"]*)?"', lambda m: f'href="/{m.group(1)}{m.group(2) or ""}"', s)
    s = s.replace('src="img/', 'src="/img/').replace('href="openapi.yaml"', 'href="/openapi.yaml"')
    s = s.replace('href="../docs/protocol.md"', 'href="/docs/protocol"')  # served by the Worker (go-live 7.5)
    return s
pages = [{'slug': slug, 'title': title, 'lede': fix(lede), **({'intro': fix(c.INTRO[slug])} if getattr(c, 'INTRO', {}).get(slug) else {}),
          'sections': [{'id': i, 'h': fix(h), 'body': fix(b)} for i, h, b in secs]}
         for slug, title, lede, secs in c.PAGES]
json.dump(pages, open(os.path.join(SITE, 'src', 'content', 'pages.json'), 'w'), indent=1, ensure_ascii=False)

# 3. Images the pages and layout use.
for name in ['shwarm-mark.png', 'shawarma.jpg', 'guide-storage.jpg']:
    shutil.copy(os.path.join(MOCK, 'img', name), os.path.join(SITE, 'static', 'img', name))
print('exported site.css,', len(pages), 'pages, images')
